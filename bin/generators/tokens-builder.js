import fs from 'fs';
import path from 'path';

/**
 * Transforms JSON tokens into CSS Custom Properties, Tailwind config, and TS definitions.
 */
export function buildTokens(inputFile = 'design-tokens.json', outputDir = './styles') {
  let rawData;
  const resolvedInput = path.resolve(process.cwd(), inputFile);
  
  if (fs.existsSync(resolvedInput)) {
    try {
      rawData = JSON.parse(fs.readFileSync(resolvedInput, 'utf-8'));
    } catch (e) {
      console.error(`❌ Failed to parse token file: ${resolvedInput}`, e.message);
      return false;
    }
  } else {
    // Default fallback design token structure
    rawData = {
      theme: "light",
      colors: {
        primary: {
          50: "#EEF2FF",
          100: "#E0E7FF",
          500: "#6366F1",
          600: "#4F46E5",
          700: "#4338CA",
          900: "#312E81"
        },
        neutral: {
          50: "#F9FAFB",
          100: "#F3F4F6",
          200: "#E5E7EB",
          500: "#6B7280",
          800: "#1F2937",
          900: "#111827"
        },
        semantic: {
          success: "#10B981",
          warning: "#F59E0B",
          danger: "#EF4444",
          info: "#3B82F6"
        }
      },
      darkColors: {
        surface: {
          ground: "#090A0F",
          base: "#12141A",
          elevated: "#1A1D24",
          highest: "#242832"
        },
        text: {
          primary: "#F3F4F6",
          secondary: "#9CA3AF",
          muted: "#6B7280"
        },
        border: {
          subtle: "#1F2937",
          default: "#374151"
        }
      },
      spacing: {
        xs: "4px",
        sm: "8px",
        md: "16px",
        lg: "24px",
        xl: "32px",
        "2xl": "48px"
      },
      radius: {
        sm: "4px",
        md: "8px",
        lg: "12px",
        full: "9999px"
      },
      typography: {
        fontFamilyHeading: "Inter, -apple-system, sans-serif",
        fontFamilyBody: "Inter, -apple-system, sans-serif",
        scale: {
          xs: "0.75rem",
          sm: "0.875rem",
          base: "1rem",
          lg: "1.125rem",
          xl: "1.25rem",
          "2xl": "1.5rem",
          "3xl": "1.875rem",
          "4xl": "2.25rem"
        }
      }
    };
  }

  const outPath = path.resolve(process.cwd(), outputDir);
  fs.mkdirSync(outPath, { recursive: true });

  // 1. Generate tokens.css
  let css = `/**
 * @generated by Agentway tokens:build
 * Single Source of Truth — CSS Custom Properties
 */

:root {
  /* Colors */
`;

  if (rawData.colors?.primary) {
    for (const [shade, val] of Object.entries(rawData.colors.primary)) {
      css += `  --color-primary-${shade}: ${val};\n`;
    }
  }

  if (rawData.colors?.neutral) {
    for (const [shade, val] of Object.entries(rawData.colors.neutral)) {
      css += `  --color-neutral-${shade}: ${val};\n`;
    }
  }

  if (rawData.colors?.semantic) {
    for (const [name, val] of Object.entries(rawData.colors.semantic)) {
      css += `  --color-semantic-${name}: ${val};\n`;
    }
  }

  // Light surfaces
  css += `
  /* Light Theme Surfaces & Text */
  --surface-ground: #F9FAFB;
  --surface-base: #FFFFFF;
  --surface-elevated: #FFFFFF;
  --surface-highest: #F3F4F6;
  --text-primary: #111827;
  --text-secondary: #4B5563;
  --text-muted: #9CA3AF;
  --border-subtle: #E5E7EB;
  --border-default: #D1D5DB;

  /* Spacing Scale (4pt/8pt Base) */
`;

  if (rawData.spacing) {
    for (const [name, val] of Object.entries(rawData.spacing)) {
      css += `  --space-${name}: ${val};\n`;
    }
  }

  css += `\n  /* Border Radius */\n`;
  if (rawData.radius) {
    for (const [name, val] of Object.entries(rawData.radius)) {
      css += `  --radius-${name}: ${val};\n`;
    }
  }

  css += `\n  /* Typography Scale */\n`;
  if (rawData.typography?.scale) {
    for (const [name, val] of Object.entries(rawData.typography.scale)) {
      css += `  --text-${name}: ${val};\n`;
    }
  }

  css += `  --font-heading: ${rawData.typography?.fontFamilyHeading || 'sans-serif'};\n`;
  css += `  --font-body: ${rawData.typography?.fontFamilyBody || 'sans-serif'};\n`;
  css += `}\n\n`;

  // Dark Mode Elevation
  css += `[data-theme="dark"], .dark {\n`;
  if (rawData.darkColors?.surface) {
    css += `  --surface-ground: ${rawData.darkColors.surface.ground || '#090A0F'};\n`;
    css += `  --surface-base: ${rawData.darkColors.surface.base || '#12141A'};\n`;
    css += `  --surface-elevated: ${rawData.darkColors.surface.elevated || '#1A1D24'};\n`;
    css += `  --surface-highest: ${rawData.darkColors.surface.highest || '#242832'};\n`;
  } else {
    css += `  --surface-ground: #090A0F;\n  --surface-base: #12141A;\n  --surface-elevated: #1A1D24;\n  --surface-highest: #242832;\n`;
  }

  if (rawData.darkColors?.text) {
    css += `  --text-primary: ${rawData.darkColors.text.primary || '#F3F4F6'};\n`;
    css += `  --text-secondary: ${rawData.darkColors.text.secondary || '#9CA3AF'};\n`;
    css += `  --text-muted: ${rawData.darkColors.text.muted || '#6B7280'};\n`;
  } else {
    css += `  --text-primary: #F3F4F6;\n  --text-secondary: #9CA3AF;\n  --text-muted: #6B7280;\n`;
  }

  if (rawData.darkColors?.border) {
    css += `  --border-subtle: ${rawData.darkColors.border.subtle || '#1F2937'};\n`;
    css += `  --border-default: ${rawData.darkColors.border.default || '#374151'};\n`;
  } else {
    css += `  --border-subtle: #1F2937;\n  --border-default: #374151;\n`;
  }
  css += `}\n`;

  fs.writeFileSync(path.join(outPath, 'tokens.css'), css, 'utf-8');

  // 2. Generate tokens.tailwind.js
  const tailwindJs = `/**
 * @generated by Agentway tokens:build
 * Tailwind CSS Theme Configuration Extension
 */
module.exports = {
  theme: {
    extend: {
      colors: {
        primary: {
          50: 'var(--color-primary-50)',
          100: 'var(--color-primary-100)',
          500: 'var(--color-primary-500)',
          600: 'var(--color-primary-600)',
          700: 'var(--color-primary-700)',
          900: 'var(--color-primary-900)'
        },
        surface: {
          ground: 'var(--surface-ground)',
          base: 'var(--surface-base)',
          elevated: 'var(--surface-elevated)',
          highest: 'var(--surface-highest)'
        },
        content: {
          primary: 'var(--text-primary)',
          secondary: 'var(--text-secondary)',
          muted: 'var(--text-muted)'
        }
      },
      spacing: {
        xs: 'var(--space-xs)',
        sm: 'var(--space-sm)',
        md: 'var(--space-md)',
        lg: 'var(--space-lg)',
        xl: 'var(--space-xl)',
        '2xl': 'var(--space-2xl)'
      },
      borderRadius: {
        sm: 'var(--radius-sm)',
        md: 'var(--radius-md)',
        lg: 'var(--radius-lg)',
        full: 'var(--radius-full)'
      },
      fontFamily: {
        heading: ['var(--font-heading)'],
        body: ['var(--font-body)']
      }
    }
  }
};
`;
  fs.writeFileSync(path.join(outPath, 'tokens.tailwind.js'), tailwindJs, 'utf-8');

  // 3. Generate tokens.d.ts
  const dts = `/**
 * @generated by Agentway tokens:build
 * TypeScript Design Token Definitions
 */

export type PrimaryColorShade = 50 | 100 | 500 | 600 | 700 | 900;
export type SpacingToken = 'xs' | 'sm' | 'md' | 'lg' | 'xl' | '2xl';
export type RadiusToken = 'sm' | 'md' | 'lg' | 'full';
export type SurfaceLevel = 'ground' | 'base' | 'elevated' | 'highest';
export type ThemeMode = 'light' | 'dark';

export interface DesignTokens {
  theme: ThemeMode;
  colors: Record<string, string | Record<string, string>>;
  spacing: Record<SpacingToken, string>;
  radius: Record<RadiusToken, string>;
}
`;
  fs.writeFileSync(path.join(outPath, 'tokens.d.ts'), dts, 'utf-8');

  return {
    css: path.join(outPath, 'tokens.css'),
    tailwind: path.join(outPath, 'tokens.tailwind.js'),
    dts: path.join(outPath, 'tokens.d.ts')
  };
}
