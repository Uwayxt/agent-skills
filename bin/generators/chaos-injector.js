export function injectChaos(targetDir = '.') {
  const outputDir = path.resolve(targetDir, 'chaos-tests');
  
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }
  
  const files = [
    { name: 'text-explosion.test.ts', content: TEXT_EXPLOSION_TEST },
    { name: 'data-extremes.test.ts', content: DATA_EXTREMES_TEST },
    { name: 'network-chaos.test.ts', content: NETWORK_CHAOS_TEST },
    { name: 'chaos-vectors.json', content: JSON.stringify(CHAOS_VECTORS, (key, value) => {
      // JSON can't represent NaN/Infinity — convert to strings
      if (typeof value === 'number' && !isFinite(value)) return String(value);
      return value;
    }, 2) },
  ];
  
  for (const { name, content } of files) {
    const filePath = path.join(outputDir, name);
    fs.writeFileSync(filePath, content, 'utf8');
  }
  
  return { outputDir, files: files.map(f => path.join(outputDir, f.name)) };
}
